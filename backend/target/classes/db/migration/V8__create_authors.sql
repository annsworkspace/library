CREATE TABLE authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL
);

CREATE UNIQUE INDEX uq_authors_name_case_insensitive
    ON authors (LOWER(name));

INSERT INTO authors (name)
SELECT MIN(BTRIM(author))
FROM books
WHERE BTRIM(author) <> ''
GROUP BY LOWER(BTRIM(author));

ALTER TABLE books
    ADD COLUMN author_id BIGINT;

UPDATE books book
SET author_id = author.id
FROM authors author
WHERE LOWER(BTRIM(book.author)) = LOWER(author.name);

ALTER TABLE books
    ALTER COLUMN author_id SET NOT NULL;

ALTER TABLE books
    ADD CONSTRAINT fk_books_author
    FOREIGN KEY (author_id) REFERENCES authors(id);

CREATE INDEX idx_books_author_id ON books(author_id);

